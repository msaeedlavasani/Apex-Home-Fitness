/**
 * Idempotency tests for `POST /api/generate-program`.
 *
 * Two layers:
 *  1. Pure contract tests (no DB): Idempotency-Key format validation and the
 *     deterministic request-body hash.
 *  2. State-machine tests against a REAL scratch SQLite database (created in a
 *     temp dir via `prisma db push`): success → exact retry replay, concurrent
 *     duplicates, key-reuse conflicts, failed-attempt retry, and stale-lock
 *     reclaim. Verifies the core guarantee: retries and duplicates never
 *     persist a second program.
 *
 * No secrets, no real user data. Runs offline (`db push` against a local file).
 */
import assert from 'node:assert/strict';
import {after, before, test} from 'node:test';
import {execFileSync} from 'node:child_process';
import {mkdtempSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {PrismaClient} from '@prisma/client';

import {isValidIdempotencyKey, requestHashOf} from '../src/lib/ai/idempotency';
import {GENERATE_PROGRAM_INPUT_SCHEMA} from '../src/lib/ai/requestSecurity';
import type {SaveGeneratedProgramInput} from '../src/services/programService';

// ---------------------------------------------------------------------------
// Scratch database setup
// ---------------------------------------------------------------------------

const tmpDir = mkdtempSync(join(tmpdir(), 'idempotency-test-'));
const dbUrl = `file:${join(tmpDir, 'idempotency-test.db')}`;

// Must be set BEFORE any module that constructs a PrismaClient is imported
// (the shared singleton in src/lib/prisma is only reached via dynamic imports
// below, which run inside `before`).
process.env.DATABASE_URL = dbUrl;

let client: PrismaClient;
let services: typeof import('../src/services/generationIdempotency');
let programService: typeof import('../src/services/programService');
let userId: string;

before(async () => {
  const prismaCli = join(process.cwd(), 'node_modules', 'prisma', 'build', 'index.js');
  execFileSync(process.execPath, [prismaCli, 'db', 'push', '--skip-generate'], {
    env: {...process.env, DATABASE_URL: dbUrl},
    stdio: 'pipe',
    timeout: 60_000,
  });

  services = await import('../src/services/generationIdempotency');
  programService = await import('../src/services/programService');
  client = new PrismaClient();

  const user = await client.user.create({
    data: {
      email: `idem-${Date.now()}@test.local`,
      name: 'Idempotency Tester',
      passwordHash: 'test-only',
    },
  });
  userId = user.id;
});

after(async () => {
  await client?.$disconnect();
  rmSync(tmpDir, {recursive: true, force: true});
});

