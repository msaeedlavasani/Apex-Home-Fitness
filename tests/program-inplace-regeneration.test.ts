/**
 * In-place program regeneration tests.
 *
 * Regeneration (a quiz re-completion or a preferences save, incl. rest-day
 * changes) must UPDATE the user's existing program row instead of inserting a
 * new one, so:
 *   - `WorkoutSession.programId` history stays attached to the SAME program,
 *   - no orphaned `Program` rows accumulate per user,
 *   - `QuizResponse.recommendedProgramId` / generation-ledger `programId`
 *     references keep pointing at a live program.
 *
 * Verified against a REAL scratch SQLite database (temp dir via `prisma db
 * push`, same pattern as `tests/idempotency.test.ts`):
 *   1. second persist replaces content in place (same id, restDays /
 *      sessionsPerWeek / exercise links swapped),
 *   2. completed workout sessions survive a regeneration unchanged and stay
 *      linked to the same program id,
 *   3. idempotent regeneration with a fresh key also updates the same row.
 *
 * No secrets, no real user data. Runs offline.
 */
import assert from 'node:assert/strict';
import {after, before, test} from 'node:test';
import {execFileSync} from 'node:child_process';
import {mkdtempSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {PrismaClient} from '@prisma/client';

import type {SaveGeneratedProgramInput} from '../src/services/programService';

// ---------------------------------------------------------------------------
// Scratch database setup
// ---------------------------------------------------------------------------

const tmpDir = mkdtempSync(join(tmpdir(), 'inplace-regeneration-test-'));
const dbUrl = `file:${join(tmpDir, 'inplace-regeneration-test.db')}`;

// Must be set BEFORE any module that constructs a PrismaClient is imported.
process.env.DATABASE_URL = dbUrl;

let client: PrismaClient;
let programService: typeof import('../src/services/programService');
let generationIdempotency: typeof import('../src/services/generationIdempotency');
let userId: string;

const WEEKDAYS = ['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday'] as const;

before(async () => {
  const prismaCli = join(process.cwd(), 'node_modules', 'prisma', 'build', 'index.js');
  execFileSync(process.execPath, [prismaCli, 'db', 'push', '--skip-generate'], {
    env: {...process.env, DATABASE_URL: dbUrl},
    stdio: 'pipe',
    timeout: 60_000,
  });

  programService = await import('../src/services/programService');
  generationIdempotency = await import('../src/services/generationIdempotency');
  client = new PrismaClient();

  const user = await client.user.create({
    data: {
      email: `inplace-${Date.now()}@test.local`,
      name: 'In-place Tester',
      passwordHash: 'test-only',
    },
  });
  userId = user.id;
});

after(async () => {
  await client?.$disconnect();
  rmSync(tmpDir, {recursive: true, force: true});
});

