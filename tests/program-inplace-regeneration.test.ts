/** One exercise for a given weekday (names are deterministic per weekday). */
function weekdayExercise(programId: string, weekday: string): SaveGeneratedProgramInput['program']['weekly_schedule'][number]['exercises'][number] {
  return {
    id: `ex_${programId}_${weekday}`,
    name: `Ex-${weekday}`,
    method: 'strength',
    equipment: 'dumbbell',
    sets: 3,
    reps: '8-10',
    rest_seconds: 90,
    tempo: '2-0-2',
    rpe: 7,
    instruction_cue: `Do ${weekday}.`,
    alternatives: [],
    contraindicated_for: [],
  };
}

/** A 7-session program (one per weekday) — every exercise name unique. */
function sampleProgram(programId: string): SaveGeneratedProgramInput['program'] {
  return {
    mode: 'general',
    program_id: programId,
    method_mix: {
      strength_pct: 40,
      hypertrophy_pct: 20,
      cardio_pct: 15,
      mobility_pct: 10,
      pilates_pct: 0,
      bodyweight_pct: 15,
      isometric_pct: 0,
    },
    weekly_schedule: WEEKDAYS.map((weekday, index) => ({
      day: index + 1,
      day_name: weekday,
      focus: `Focus ${weekday}`,
      warmup: [],
      exercises: [weekdayExercise(programId, weekday)],
      cooldown: [],
    })),
    progression_plan: {
      weeks_1_2: 'x',
      weeks_3_5: 'y',
      week_6: 'z',
      overload_variables: ['sets'],
    },
    warnings: [],
    notes: 'Generated by tests.',
    disclaimer: 'Test disclaimer.',
  };
}

async function linkedExerciseNames(programId: string): Promise<string[]> {
  const links = await client.programExercise.findMany({
    where: {programId},
    include: {exercise: {select: {name: true}}},
    orderBy: {order: 'asc'},
  });
  return links.map((link) => link.exercise.name);
}

