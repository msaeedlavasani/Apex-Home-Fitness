test('regeneration replaces the user program IN PLACE — same id, no new row', async () => {
  const first = await programService.persistProgramForUser(userId, {
    program: sampleProgram('prog-v1'),
    level: 'beginner',
    goal: 'strength',
    restDays: ['monday'],
  });
  assert.equal(first.ownerId, userId);
  assert.equal(await client.program.count({where: {ownerId: userId}}), 1);
  // With restDays ['monday'], 6 of the 7 sessions carry workouts.
  assert.equal(first.sessionsPerWeek, 6);

  const second = await programService.persistProgramForUser(userId, {
    program: sampleProgram('prog-v2'),
    level: 'intermediate',
    goal: 'fat_loss',
    restDays: ['thursday', 'friday'],
  });

  // Same row, replaced content.
  assert.equal(second.id, first.id);
  assert.equal(await client.program.count({where: {ownerId: userId}}), 1);
  assert.deepEqual(second.restDays, ['thursday', 'friday']);
  assert.equal(second.sessionsPerWeek, 5);
  assert.equal(second.name, 'AI Program prog-v2');
  assert.equal(await client.program.count({where: {name: 'AI Program prog-v1'}}), 0);

  // Exercise links replaced: thursday/friday are now rest days (skipped),
  // monday is no longer a rest day (linked again).
  const names = await linkedExerciseNames(second.id);
  assert.ok(names.includes('Ex-monday'));
  assert.ok(!names.includes('Ex-thursday'));
  assert.ok(!names.includes('Ex-friday'));
  assert.equal(names.length, 5);
});

test('stored workout history stays attached across in-place regeneration', async () => {
  const program = await programService.persistProgramForUser(userId, {
    program: sampleProgram('prog-h1'),
    level: 'beginner',
    goal: 'strength',
    restDays: ['monday'],
  });
  const exercise = await client.exercise.findUniqueOrThrow({where: {name: 'Ex-monday'}});
  const session = await client.workoutSession.create({
    data: {
      userId,
      programId: program.id,
      startedAt: new Date('2026-08-01T10:00:00.000Z'),
      completedAt: new Date('2026-08-01T10:45:00.000Z'),
      durationSeconds: 2700,
      exercises: {
        create: [{exerciseId: exercise.id, order: 0, completed: true, actualSets: 3, actualReps: 10}],
      },
    },
  });

  // Regenerate with different rest days — the SAME program row is updated.
  const next = await programService.persistProgramForUser(userId, {
    program: sampleProgram('prog-h2'),
    level: 'intermediate',
    goal: 'fat_loss',
    restDays: ['friday'],
  });
  assert.equal(next.id, program.id);

  // The completed session and its performed exercises survive untouched.
  const kept = await client.workoutSession.findUniqueOrThrow({where: {id: session.id}});
  assert.equal(kept.programId, program.id);
  const keptExercises = await client.workoutSessionExercise.findMany({where: {sessionId: session.id}});
  assert.equal(keptExercises.length, 1);
  assert.equal(keptExercises[0].exerciseId, exercise.id);
  assert.equal(keptExercises[0].completed, true);

  // The program's own links were replaced with the new prescription:
  // monday is a training day again (linked), friday is the new rest day
  // (no link), and the rest-day session from the old program is gone.
  const names = await linkedExerciseNames(program.id);
  assert.ok(names.includes('Ex-monday'));
  assert.ok(!names.includes('Ex-friday'));
  assert.equal(names.length, 6); // friday is the only rest day now
});

test('idempotent regeneration with a fresh key updates the SAME program row', async () => {
  const bodyA = {level: 'beginner', goal: 'strength', equipment: ['dumbbells', 'bench'], limitations: [], limitationsDetails: ''};

  const keyA = `inplace-a-${Date.now()}`;
  const claimA = await generationIdempotency.beginIdempotentGeneration(userId, keyA, bodyA, {client});
  assert.equal(claimA.kind, 'claimed');
  if (claimA.kind !== 'claimed') return;
  const programA = await programService.persistProgramForUserWithIdempotency(
    userId,
    {program: sampleProgram('prog-i1'), level: 'beginner', goal: 'strength', restDays: ['monday'], idempotencyRecordId: claimA.record.id},
    client,
  );

  // A second, independent generation (fresh key) replaces the same row.
  const keyB = `inplace-b-${Date.now()}`;
  const bodyB = {...bodyA, goal: 'fat_loss'};
  const claimB = await generationIdempotency.beginIdempotentGeneration(userId, keyB, bodyB, {client});
  assert.equal(claimB.kind, 'claimed');
  if (claimB.kind !== 'claimed') return;
  const programB = await programService.persistProgramForUserWithIdempotency(
    userId,
    {program: sampleProgram('prog-i2'), level: 'intermediate', goal: 'fat_loss', restDays: ['friday'], idempotencyRecordId: claimB.record.id},
    client,
  );

  assert.equal(programB.id, programA.id);
  assert.equal(await client.program.count({where: {ownerId: userId, name: 'AI Program prog-i2'}}), 1);
  assert.equal(await client.program.count({where: {ownerId: userId, name: 'AI Program prog-i1'}}), 0);

  // Both ledger records finalized — pointing at the same (single) program.
  const recordA = await client.programGenerationRequest.findUniqueOrThrow({
    where: {userId_idempotencyKey: {userId, idempotencyKey: keyA}},
  });
  const recordB = await client.programGenerationRequest.findUniqueOrThrow({
    where: {userId_idempotencyKey: {userId, idempotencyKey: keyB}},
  });
  assert.equal(recordA.status, 'SUCCEEDED');
  assert.equal(recordA.programId, programA.id);
  assert.equal(recordB.status, 'SUCCEEDED');
  assert.equal(recordB.programId, programA.id);
});
